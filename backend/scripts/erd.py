r"""Generates docs/ERD.md (Mermaid) from the SQLAlchemy models, so the diagram never drifts from the schema.

Run:  .venv\Scripts\python.exe -m scripts.erd
"""


import app.models  # noqa: F401  (registers every table)
from app.core.config import BACKEND_DIR
from app.db.base import Base

OUT = BACKEND_DIR / "docs" / "ERD.md"


def _type(column) -> str:
    name = column.type.__class__.__name__.lower()
    return {"uuid": "uuid", "numeric": "numeric", "datetime": "timestamptz", "jsonb": "jsonb", "biginteger": "bigint", "smallinteger": "smallint"}.get(name, name)


def render() -> str:
    lines = ["erDiagram"]
    relations = set()
    for table in sorted(Base.metadata.sorted_tables, key=lambda t: t.name):
        lines.append(f"    {table.name} {{")
        for column in table.columns:
            keys = ",".join(k for k, on in (("PK", column.primary_key), ("FK", bool(column.foreign_keys))) if on)
            lines.append(f"        {_type(column)} {column.name}{' ' + keys if keys else ''}")
        lines.append("    }")
        for fk in table.foreign_key_constraints:
            target = fk.referred_table.name
            if fk.columns.keys() in (["created_by"], ["updated_by"]):
                continue  # authorship links to users are on almost every table; omitted for readability
            optional = any(c.nullable for c in fk.columns)
            relations.add(f"    {target} ||--{'o' if optional else '|'}{{ {table.name} : \"{', '.join(fk.columns.keys())}\"")
    return "\n".join(lines + sorted(relations))


def main() -> None:
    body = render()
    tables = len(Base.metadata.tables)
    OUT.write_text(
        "# Entity relationship diagram\n\n"
        f"Generated by `scripts/erd.py` from the SQLAlchemy models ({tables} tables). Do not edit by hand.\n"
        "`created_by` / `updated_by` links to `users` are omitted for readability.\n\n"
        f"```mermaid\n{body}\n```\n",
        encoding="utf-8",
    )
    print(f"Wrote {OUT.relative_to(BACKEND_DIR)} ({tables} tables)")


if __name__ == "__main__":
    main()
